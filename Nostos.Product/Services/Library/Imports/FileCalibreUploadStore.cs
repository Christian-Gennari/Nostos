    // Assembly and extraction
    // ------------------------------------------------------------------

    private static async Task AssembleArchiveAsync(
        string directory,
        CalibreUploadManifest manifest,
        CancellationToken ct)
    {
        var archivePath = Path.Combine(directory, ArchiveFileName);
        var temp = archivePath + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
            await using (var output = new FileStream(
                temp, FileMode.CreateNew, FileAccess.Write, FileShare.None,
                CopyBufferBytes, FileOptions.Asynchronous))
            {
                var totalParts = BookUploadLimits.PartCountFor(manifest.TotalBytes);
                using var buffer = new PortableArchiveBufferBudget(CopyBufferBytes)
                    .Rent(CopyBufferBytes, ct);
                for (var index = 0; index < totalParts; index++)
                {
                    ct.ThrowIfCancellationRequested();
                    await using var input = new FileStream(
                        PartPath(directory, index), FileMode.Open, FileAccess.Read, FileShare.Read,
                        CopyBufferBytes, FileOptions.Asynchronous | FileOptions.SequentialScan);
                    int read;
                    while ((read = await input.ReadAsync(buffer.Memory, ct)) != 0)
                    {
                        hash.AppendData(buffer.Memory.Span[..read]);
                        await output.WriteAsync(buffer.Memory[..read], ct);
                    }
                }

                await output.FlushAsync(ct);
            }

            if (!string.Equals(
                    Convert.ToHexStringLower(hash.GetHashAndReset()),
                    manifest.Sha256,
                    StringComparison.OrdinalIgnoreCase))
            {
                throw CalibreUploadException.Error(
                    CalibreUploadException.FileHashMismatch,
                    "The library changed while it was uploading. Choose the same zip again.");
            }

            File.Move(temp, archivePath, overwrite: false);
        }
        catch
        {
            TryDelete(temp);
            throw;
        }
    }

    /// <summary>
    /// Extracts a Calibre zip into <paramref name="destination"/> and returns
    /// the bytes written. Every entry is checked before anything is written:
    /// rooted names, drive letters, backslashes, <c>.</c>/<c>..</c>, control
    /// characters and Windows-reserved names are refused, as are duplicate
    /// names and Unix/Windows symbolic links. Totals are enforced while
    /// copying, so a zip whose headers understate its size cannot exceed the
    /// cap either.
    /// </summary>
    private static async Task<long> ExtractAsync(
        string archivePath,
        string destination,
        CalibreUploadLimits limits,
        CancellationToken ct)
    {
        long totalBytes = 0;
        var files = 0;
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        await using var archiveStream = new FileStream(
            archivePath, FileMode.Open, FileAccess.Read, FileShare.Read,
            CopyBufferBytes, FileOptions.Asynchronous | FileOptions.SequentialScan);

        ZipArchive archive;
        try
        {
            archive = new ZipArchive(archiveStream, ZipArchiveMode.Read, leaveOpen: false);
        }
        catch (InvalidDataException)
        {
            throw CalibreUploadException.Error(
                CalibreUploadException.InvalidArchive,
                "This file is not a zip archive. Create a zip of the Calibre library folder.");
        }

        using (archive)
        {
            foreach (var entry in archive.Entries)
            {
                ct.ThrowIfCancellationRequested();

                var (segments, isDirectory) = SafeEntry(entry);
                var relative = string.Join(Path.DirectorySeparatorChar, segments);
                if (!names.Add(relative))
                {
                    throw CalibreUploadException.Error(
                        CalibreUploadException.UnsafeEntry,
                        "The zip contains the same path twice. Create it again from the Calibre library folder.");
                }

                var target = ResolveWithin(destination, relative);

                if (isDirectory)
                {
                    Directory.CreateDirectory(target);
                    continue;
                }

                files++;
                if (files > limits.MaxFiles)
                {
                    throw CalibreUploadException.Error(
                        CalibreUploadException.TooManyFiles,
                        $"A Calibre library can contain at most {limits.MaxFiles:N0} files.");
                }

                if (entry.Length > limits.MaxExtractedBytes - totalBytes)
                {
                    throw CalibreUploadException.Error(
                        CalibreUploadException.ExtractedTooLarge,
                        "The extracted Calibre library is larger than this server allows.");
                }

                var parent = Path.GetDirectoryName(target);
                if (!string.IsNullOrEmpty(parent))
                    Directory.CreateDirectory(parent);

                try
                {
                    await using var input = entry.Open();
                    await using var output = new FileStream(
                        target, FileMode.CreateNew, FileAccess.Write, FileShare.None,
                        CopyBufferBytes, FileOptions.Asynchronous);
                    using var buffer = new PortableArchiveBufferBudget(CopyBufferBytes)
                        .Rent(CopyBufferBytes, ct);
                    long written = 0;
                    int read;
                    while ((read = await input.ReadAsync(buffer.Memory, ct)) != 0)
                    {
                        written += read;
                        totalBytes += read;
                        if (totalBytes > limits.MaxExtractedBytes)
                        {
                            throw CalibreUploadException.Error(
                                CalibreUploadException.ExtractedTooLarge,
                                "The extracted Calibre library is larger than this server allows.");
                        }

                        await output.WriteAsync(buffer.Memory[..read], ct);
                    }

                    if (written != entry.Length)
                    {
                        throw CalibreUploadException.Error(
                            CalibreUploadException.InvalidArchive,
                            "The zip is damaged: a file is shorter than its recorded size.");
                    }
                }
                catch (InvalidDataException)
                {
                    throw CalibreUploadException.Error(
                        CalibreUploadException.InvalidArchive,
                        "The zip is damaged or encrypted. Create it again from the Calibre library folder.");
                }
            }
        }

        return totalBytes;
    }

    private static (string[] Segments, bool IsDirectory) SafeEntry(ZipArchiveEntry entry)
    {
        var name = entry.FullName;
        if (string.IsNullOrEmpty(name) || name.Length > CalibrePathSafety.MaxRelativePathLength)
            throw Unsafe("The zip contains an entry with an invalid name.");

        if (name.StartsWith('/') || name.StartsWith('\\') || name[1..].StartsWith(':') || name.Contains('\\'))
            throw Unsafe("The zip contains an absolute path or a Windows path. Create it from the Calibre library folder.");

        foreach (var c in name)
        {
            if (char.IsControl(c))
                throw Unsafe("The zip contains a file name with a control character.");
        }

        var isDirectory = name.EndsWith('/');
        var trimmed = isDirectory ? name[..^1] : name;
        if (trimmed.Length == 0)
            throw Unsafe("The zip contains an entry with an invalid name.");

        var segments = trimmed.Split('/');
        foreach (var segment in segments)
        {
            if (segment.Length == 0 || segment is "." or "..")
                throw Unsafe("The zip contains a path that escapes the library folder.");
            if (segment.Length > 255 || segment.IndexOfAny(InvalidSegmentCharacters) >= 0)
                throw Unsafe("The zip contains a file name this server cannot store safely.");
            if (segment.EndsWith('.') || segment.EndsWith(' '))
                throw Unsafe("The zip contains a file name this server cannot store safely.");

            var stem = segment.Split('.')[0].ToUpperInvariant();
            if (ReservedWindowsNames.Contains(stem))
                throw Unsafe("The zip contains a reserved file name this server cannot store safely.");
        }

        // A symlink (Unix mode 0xA000) or a Windows reparse point would make a
        // later read follow a path outside the uploaded library.
        var unixMode = (entry.ExternalAttributes >> 16) & 0xFFFF;
        if ((unixMode & 0xF000) == 0xA000
            || (entry.ExternalAttributes & (int)FileAttributes.ReparsePoint) != 0)
        {
            throw Unsafe("The zip contains a symbolic link. Create it without links.");
        }

        if (!isDirectory)
            isDirectory = (entry.ExternalAttributes & (int)FileAttributes.Directory) != 0;

        return (segments, isDirectory);
    }

    private static string ResolveWithin(string destination, string relative)
    {
        var full = Path.GetFullPath(Path.Combine(destination, relative));
        var root = destination.EndsWith(Path.DirectorySeparatorChar)
            ? destination
            : destination + Path.DirectorySeparatorChar;
        if (!full.StartsWith(root, PathComparison(full)))
            throw Unsafe("The zip contains a path that escapes the library folder.");
        return full;
    }

    private static string FindLibraryRoot(string extractedDirectory)
    {
        if (CalibrePathSafety.IsRegularFile(Path.Combine(extractedDirectory, "metadata.db")))
            return extractedDirectory;

        var candidates = new List<string>();
        foreach (var directory in Directory.EnumerateDirectories(extractedDirectory))
        {
            var info = new DirectoryInfo(directory);
            if (!info.Exists || CalibrePathSafety.IsLink(info))
                continue;
            if (CalibrePathSafety.IsRegularFile(Path.Combine(directory, "metadata.db")))
                candidates.Add(directory);
        }

        return candidates.Count switch
        {
            1 => candidates[0],
            0 => throw CalibreUploadException.Error(
                CalibreUploadException.MetadataMissing,
                "This zip does not hold a Calibre library: metadata.db must be at its root or in one top-level folder."),
            _ => throw CalibreUploadException.Error(
                CalibreUploadException.MetadataMissing,
                "This zip holds more than one Calibre library. Upload one library per zip."),
        };
    }

    private static CalibreUploadException Unsafe(string message) =>
        CalibreUploadException.Error(CalibreUploadException.UnsafeEntry, message);

