namespace Nostos.Backend.Services.Library.Imports;

/// <summary>
/// SelfHosted staging for an uploaded Calibre library (issue #1572).
///
/// One directory per upload holds a manifest, the parts already received, the
/// assembled zip and the safely extracted library. Nothing here is a database
/// row: the staged bytes are disposable, and replacing them with a newer
/// upload is a directory delete. Every name is generated by the server or
/// derived from a zip entry through <see cref="ExtractAsync"/>, which refuses
/// rooted paths, traversal, symbolic links, duplicate names, and any library
/// larger than the configured file/byte caps.
///
/// The parts use the same server-owned part size and per-part SHA-256 contract
/// as the resumable library transfer, so the browser can reuse its chunk
/// engine instead of sending one unbounded request body.
/// </summary>
public sealed class FileCalibreUploadStore : ICalibreUploadStore
{
    private const string ManifestFileName = "manifest.json";
    private const string PartsDirectoryName = "parts";
    private const string ArchiveFileName = "library.zip";
    private const string ExtractedDirectoryName = "extracted";
    private const int CopyBufferBytes = 128 * 1024;

    /// <summary>A directory with no manifest yet may be a session being created; leave it alone.</summary>
    private static readonly TimeSpan OrphanGrace = TimeSpan.FromMinutes(10);

    private static readonly char[] InvalidSegmentCharacters =
        ['\0', '/', '\\', ':', '*', '?', '"', '<', '>', '|'];

    private static readonly string[] ReservedWindowsNames =
    [
        "CON", "PRN", "AUX", "NUL",
        "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9",
        "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9",
    ];

    private readonly string _root;
    private readonly ConcurrentDictionary<string, SemaphoreSlim> _locks = new(StringComparer.Ordinal);
    private readonly ILogger<FileCalibreUploadStore>? _logger;

    public FileCalibreUploadStore(string rootPath, ILogger<FileCalibreUploadStore>? logger = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(rootPath);
        var full = Path.GetFullPath(rootPath);
        if (string.Equals(full, Path.GetPathRoot(full), PathComparison(full)))
            throw new InvalidOperationException(
                "The Calibre upload scratch root must be a directory below the filesystem root.");

        _root = full;
        Directory.CreateDirectory(_root);
        _logger = logger;
    }

    public string RootPath => _root;

    // ------------------------------------------------------------------
    // Sessions
    // ------------------------------------------------------------------

    public async Task<CalibreUploadManifest?> FindActiveAsync(string ownerKey, CancellationToken ct)
    {
        var newest = await ScanAsync(ownerKey, ct);
        return newest.FirstOrDefault(manifest =>
            manifest.State is CalibreUploadStates.Receiving or CalibreUploadStates.Staged);
    }

    public async Task<CalibreUploadManifest?> FindAsync(Guid sessionId, string ownerKey, CancellationToken ct)
    {
        var directory = SessionDirectory(sessionId);
        var manifest = await ReadManifestAsync(directory, ct);
        return manifest is not null
            && string.Equals(manifest.OwnerKey, ownerKey, StringComparison.Ordinal)
                ? manifest
                : null;
    }

    public async Task<CalibreUploadManifest?> FindLatestStagedAsync(string ownerKey, CancellationToken ct)
    {
        var all = await ScanAsync(ownerKey, ct);
        return all.FirstOrDefault(manifest => manifest.State == CalibreUploadStates.Staged);
    }

    public async Task<CalibreUploadManifest> CreateAsync(
        string ownerKey,
        CalibreUploadCreateRequest request,
        CalibreUploadLimits limits,
        DateTime nowUtc,
        CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(request);
        ArgumentNullException.ThrowIfNull(limits);

        var id = Guid.NewGuid();
        var directory = SessionDirectory(id);
        Directory.CreateDirectory(directory);
        Directory.CreateDirectory(Path.Combine(directory, PartsDirectoryName));

        var manifest = new CalibreUploadManifest
        {
            Id = id,
            OwnerKey = ownerKey,
            State = CalibreUploadStates.Receiving,
            FileName = SafeDisplayName(request.FileName),
            TotalBytes = request.TotalBytes,
            Sha256 = request.Sha256.ToLowerInvariant(),
            CreatedAtUtc = nowUtc,
            UpdatedAtUtc = nowUtc,
            ExpiresAtUtc = nowUtc.Add(limits.SessionLifetime),
        };
        await WriteManifestAsync(directory, manifest, ct);
        return manifest;
    }

    public async Task<CalibreUploadPartReceipt> ReceivePartAsync(
        CalibreUploadManifest session,
        int partIndex,
        long start,
        long end,
        long total,
        string expectedSha256,
        Stream content,
        CalibreUploadLimits limits,
        DateTime nowUtc,
        CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(session);
        ArgumentNullException.ThrowIfNull(content);
        ArgumentNullException.ThrowIfNull(limits);

        using var lease = await EnterAsync(session.Id, ct);
        var directory = SessionDirectory(session.Id);
        var manifest = await ReadManifestAsync(directory, ct)
            ?? throw CalibreUploadException.Error(CalibreUploadException.NotFound);
        EnsureUsable(manifest, total, limits, nowUtc);
        if (manifest.State != CalibreUploadStates.Receiving)
            throw CalibreUploadException.Error(CalibreUploadException.Failed);

        if (partIndex < 0 || partIndex >= limits.PartCountFor(total))
            throw CalibreUploadException.Error(CalibreUploadException.PartRangeInvalid);

        var expectedLength = limits.PartLengthFor(total, partIndex);
        var expectedStart = (long)partIndex * limits.PartBytes;
        if (expectedLength <= 0
            || start != expectedStart
            || end != expectedStart + expectedLength - 1)
        {
            throw CalibreUploadException.Error(CalibreUploadException.PartRangeInvalid);
        }

        var parts = Path.Combine(directory, PartsDirectoryName);
        Directory.CreateDirectory(parts);
        var partPath = PartPath(directory, partIndex);

        if (File.Exists(partPath))
        {
            var stored = await HashFileAsync(partPath, ct);
            if (!string.Equals(stored, expectedSha256, StringComparison.OrdinalIgnoreCase))
                throw CalibreUploadException.Error(CalibreUploadException.PartConflict);

            Touch(manifest, limits, nowUtc);
            await WriteManifestAsync(directory, manifest, ct);
            return new CalibreUploadPartReceipt(manifest.Id, partIndex, AlreadyPresent: true);
        }

        var temp = PartPath(directory, partIndex) + "." + Guid.NewGuid().ToString("N") + ".tmp";
        var outcome = await ResumablePartReceiver.ReceiveIntoAsync(
            () => new FileStream(
                temp, FileMode.CreateNew, FileAccess.Write, FileShare.None,
                ResumablePartReceiver.BufferBytes, FileOptions.Asynchronous),
            () => TryDelete(temp),
            content,
            expectedLength,
            expectedSha256,
            ct);
        if (outcome == ResumablePartOutcome.RangeInvalid)
            throw CalibreUploadException.Error(CalibreUploadException.PartRangeInvalid);
        if (outcome == ResumablePartOutcome.HashMismatch)
            throw CalibreUploadException.Error(CalibreUploadException.PartHashMismatch);

        try
        {
            File.Move(temp, partPath, overwrite: false);
        }
        catch
        {
            TryDelete(temp);
            throw;
        }

        if (!manifest.ReceivedParts.Contains(partIndex))
            manifest.ReceivedParts.Add(partIndex);
        manifest.ReceivedParts.Sort();
        Touch(manifest, limits, nowUtc);
        await WriteManifestAsync(directory, manifest, ct);
        return new CalibreUploadPartReceipt(manifest.Id, partIndex, AlreadyPresent: false);
    }

    public async Task<CalibreStagedLibrary?> ReadStagedAsync(
        CalibreUploadManifest session,
        CancellationToken ct)
    {
        var directory = SessionDirectory(session.Id);
        var manifest = await ReadManifestAsync(directory, ct);
        return manifest is null ? null : ResolveStaged(directory, manifest);
    }

    public async Task<CalibreStagedLibrary> StageAsync(
        CalibreUploadManifest session,
        CalibreUploadLimits limits,
        DateTime nowUtc,
        CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(session);
        ArgumentNullException.ThrowIfNull(limits);

        using var lease = await EnterAsync(session.Id, ct);
        var directory = SessionDirectory(session.Id);
        var manifest = await ReadManifestAsync(directory, ct)
            ?? throw CalibreUploadException.Error(CalibreUploadException.NotFound);

        if (manifest.State == CalibreUploadStates.Staged
            && ResolveStaged(directory, manifest) is { } already)
        {
            return already;
        }

        if (manifest.State == CalibreUploadStates.Failed)
        {
            throw CalibreUploadException.Error(
                manifest.FailureCode ?? CalibreUploadException.Failed,
                manifest.FailureMessage);
        }

        EnsureUsable(manifest, manifest.TotalBytes, limits, nowUtc);

        var totalParts = limits.PartCountFor(manifest.TotalBytes);
        var missing = Enumerable.Range(0, totalParts)
            .Where(index => !manifest.ReceivedParts.Contains(index))
            .ToList();
        if (missing.Count > 0)
        {
            throw new CalibreUploadException(
                CalibreUploadException.Incomplete,
                $"The upload is missing {missing.Count} of {totalParts} parts.",
                missing);
        }

        var archivePath = Path.Combine(directory, ArchiveFileName);
        try
        {
            if (!File.Exists(archivePath))
                await AssembleArchiveAsync(directory, manifest, ct);
            else if (!string.Equals(
                         await HashFileAsync(archivePath, ct),
                         manifest.Sha256,
                         StringComparison.OrdinalIgnoreCase))
            {
                File.Delete(archivePath);
                await AssembleArchiveAsync(directory, manifest, ct);
            }

            var extractedDirectory = Path.Combine(directory, ExtractedDirectoryName);
            if (Directory.Exists(extractedDirectory))
                Directory.Delete(extractedDirectory, recursive: true);
            Directory.CreateDirectory(extractedDirectory);

            var stagedBytes = await ExtractAsync(archivePath, extractedDirectory, limits, ct);
            var root = FindLibraryRoot(extractedDirectory);
            var books = await new CalibreLibraryReader(root).CountBooksAsync(ct);

            var relativeRoot = Path.GetRelativePath(directory, root);
            manifest.State = CalibreUploadStates.Staged;
            manifest.StagedRoot = relativeRoot;
            manifest.StagedBytes = stagedBytes;
            manifest.Books = books;
            manifest.FailureCode = null;
            manifest.FailureMessage = null;
            Touch(manifest, limits, nowUtc);
            await WriteManifestAsync(directory, manifest, ct);

            // The zip and its parts have done their job. Keeping them would
            // double the scratch a large library needs for its whole lifetime.
            DeletePartsAndArchive(directory);

            return new CalibreStagedLibrary(manifest.Id, root, stagedBytes, books);
        }
        catch (OperationCanceledException) when (ct.IsCancellationRequested)
        {
            throw;
        }
        catch (CalibreUploadException)
        {
            MarkFailed(directory);
            throw;
        }
        catch (CalibreLibraryException exception)
        {
            MarkFailed(directory);
            throw CalibreUploadException.Error(CalibreUploadException.NotCalibre, exception.Message);
        }
        catch (Exception exception) when (exception is InvalidDataException
            or IOException
            or UnauthorizedAccessException
            or NotSupportedException)
        {
            MarkFailed(directory);
            throw CalibreUploadException.Error(
                CalibreUploadException.InvalidArchive,
                "The zip could not be read. Create it again from the Calibre library folder.");
        }
    }

    public Task DiscardAsync(CalibreUploadManifest session, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(session);
        var directory = SessionDirectory(session.Id);
        DeleteDirectory(directory);
        return Task.CompletedTask;
    }

    public async Task<int> ExpireAsync(DateTime cutoffUtc, CancellationToken ct)
    {
        var removed = 0;
        foreach (var directory in EnumerateSessionDirectories())
        {
            ct.ThrowIfCancellationRequested();
            var manifest = await ReadManifestAsync(directory, ct);
            if (manifest is not null)
            {
                if (manifest.ExpiresAtUtc > cutoffUtc)
                    continue;
            }
            else if (NewestWriteUtc(directory) > cutoffUtc - OrphanGrace)
            {
                continue;
            }

            DeleteDirectory(directory);
            removed++;
        }

        return removed;
    }

