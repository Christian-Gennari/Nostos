    private static void EnsureUsable(
        CalibreUploadManifest manifest,
        long total,
        CalibreUploadLimits limits,
        DateTime nowUtc)
    {
        if (manifest.ExpiresAtUtc <= nowUtc)
            throw CalibreUploadException.Error(
                CalibreUploadException.Expired,
                "This upload expired. Choose the zip again to start over.");
        if (total != manifest.TotalBytes)
            throw CalibreUploadException.Error(CalibreUploadException.PartRangeInvalid);
        if (manifest.TotalBytes > limits.MaxLibraryBytes)
            throw CalibreUploadException.Error(
                CalibreUploadException.TooLarge,
                "This library is larger than this server allows.");
        if (manifest.State == CalibreUploadStates.Failed)
            throw CalibreUploadException.Error(
                manifest.FailureCode ?? CalibreUploadException.Failed,
                manifest.FailureMessage);
    }

    private static void Touch(CalibreUploadManifest manifest, CalibreUploadLimits limits, DateTime nowUtc)
    {
        manifest.UpdatedAtUtc = nowUtc;
        manifest.ExpiresAtUtc = nowUtc.Add(limits.SessionLifetime);
    }

    private static CalibreStagedLibrary? ResolveStaged(string directory, CalibreUploadManifest manifest)
    {
        if (manifest.State != CalibreUploadStates.Staged
            || manifest.StagedRoot is null
            || manifest.StagedBytes is null
            || manifest.Books is null)
        {
            return null;
        }

        var root = Path.GetFullPath(Path.Combine(directory, manifest.StagedRoot));
        if (!root.StartsWith(
                directory.EndsWith(Path.DirectorySeparatorChar) ? directory : directory + Path.DirectorySeparatorChar,
                PathComparison(root)))
        {
            return null;
        }

        return CalibrePathSafety.IsRegularFile(Path.Combine(root, "metadata.db"))
            ? new CalibreStagedLibrary(manifest.Id, root, manifest.StagedBytes.Value, manifest.Books.Value)
            : null;
    }

    /// <summary>
    /// A zip that cannot become a library leaves nothing behind: the request
    /// that failed already carries the reason, and a partial extraction is not
    /// something a later retry can use. The owner chooses the zip again.
    /// </summary>
    private static void MarkFailed(string directory) => DeleteDirectory(directory);

    private static void DeletePartsAndArchive(string directory)
    {
        DeleteDirectory(Path.Combine(directory, PartsDirectoryName));
        TryDelete(Path.Combine(directory, ArchiveFileName));
        TryDelete(Path.Combine(directory, ArchiveFileName) + ".tmp");
    }

    private async Task<List<CalibreUploadManifest>> ScanAsync(string ownerKey, CancellationToken ct)
    {
        var manifests = new List<CalibreUploadManifest>();
        foreach (var directory in EnumerateSessionDirectories())
        {
            ct.ThrowIfCancellationRequested();
            var manifest = await ReadManifestAsync(directory, ct);
            if (manifest is not null
                && string.Equals(manifest.OwnerKey, ownerKey, StringComparison.Ordinal))
            {
                manifests.Add(manifest);
            }
        }

        return manifests.OrderByDescending(manifest => manifest.UpdatedAtUtc).ToList();
    }

    private IEnumerable<string> EnumerateSessionDirectories()
    {
        foreach (var directory in Directory.EnumerateDirectories(_root))
        {
            var name = Path.GetFileName(directory);
            if (name.Length == 32
                && Guid.TryParseExact(name, "N", out var id)
                && id != Guid.Empty)
            {
                yield return directory;
            }
        }
    }

    private string SessionDirectory(Guid sessionId)
    {
        if (sessionId == Guid.Empty)
            throw CalibreUploadException.Error(CalibreUploadException.InvalidRequest);
        var directory = Path.Combine(_root, sessionId.ToString("N"));
        if (!directory.StartsWith(
                _root.EndsWith(Path.DirectorySeparatorChar) ? _root : _root + Path.DirectorySeparatorChar,
                PathComparison(directory)))
        {
            throw new InvalidOperationException("A Calibre upload path escaped the scratch root.");
        }

        return directory;
    }

    private static string PartPath(string sessionDirectory, int partIndex)
    {
        if (partIndex < 0)
            throw CalibreUploadException.Error(CalibreUploadException.PartRangeInvalid);
        return Path.Combine(sessionDirectory, PartsDirectoryName, $"{partIndex:D8}.part");
    }

    private async Task<CalibreUploadManifest?> ReadManifestAsync(string directory, CancellationToken ct)
    {
        var path = Path.Combine(directory, ManifestFileName);
        if (!File.Exists(path))
            return null;

        try
        {
            await using var stream = new FileStream(
                path, FileMode.Open, FileAccess.Read, FileShare.Read,
                CopyBufferBytes, FileOptions.Asynchronous | FileOptions.SequentialScan);
            return await JsonSerializer.DeserializeAsync<CalibreUploadManifest>(
                stream, CalibreUploadJson.Options, ct);
        }
        catch (Exception exception) when (exception is JsonException
            or IOException
            or UnauthorizedAccessException)
        {
            _logger?.LogWarning(
                "A Calibre upload manifest could not be read; it will expire with its scratch. Exception type {ExceptionType}.",
                exception.GetType().Name);
            return null;
        }
    }

    private static async Task WriteManifestAsync(
        string directory,
        CalibreUploadManifest manifest,
        CancellationToken ct)
    {
        Directory.CreateDirectory(directory);
        var path = Path.Combine(directory, ManifestFileName);
        var temp = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        await using (var stream = new FileStream(
            temp, FileMode.CreateNew, FileAccess.Write, FileShare.None,
            CopyBufferBytes, FileOptions.Asynchronous))
        {
            await JsonSerializer.SerializeAsync(stream, manifest, CalibreUploadJson.Options, ct);
            await stream.FlushAsync(ct);
        }

        File.Move(temp, path, overwrite: true);
    }

    private async Task<SemaphoreLease> EnterAsync(Guid sessionId, CancellationToken ct)
    {
        var gate = _locks.GetOrAdd(sessionId.ToString("N"), _ => new SemaphoreSlim(1, 1));
        await gate.WaitAsync(ct);
        return new SemaphoreLease(gate);
    }

    private static async Task<string> HashFileAsync(string path, CancellationToken ct)
    {
        await using var stream = new FileStream(
            path, FileMode.Open, FileAccess.Read, FileShare.Read,
            CopyBufferBytes, FileOptions.Asynchronous | FileOptions.SequentialScan);
        using var buffer = new PortableArchiveBufferBudget(CopyBufferBytes)
            .Rent(CopyBufferBytes, ct);
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        int read;
        while ((read = await stream.ReadAsync(buffer.Memory, ct)) != 0)
            hash.AppendData(buffer.Memory.Span[..read]);
        return Convert.ToHexStringLower(hash.GetHashAndReset());
    }

    private static string SafeDisplayName(string? fileName)
    {
        var name = string.IsNullOrWhiteSpace(fileName)
            ? "library.zip"
            : Path.GetFileName(fileName.Replace('\\', '/'));
        name = new string(name.Where(c => !char.IsControl(c)).ToArray()).Trim();
        if (name.Length == 0)
            return "library.zip";
        return name.Length <= 200 ? name : name[..200];
    }

    private static DateTime NewestWriteUtc(string directory)
    {
        try
        {
            var newest = Directory.GetLastWriteTimeUtc(directory);
            foreach (var file in Directory.EnumerateFiles(directory, "*", SearchOption.AllDirectories))
                newest = Max(newest, File.GetLastWriteTimeUtc(file));
            return newest;
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            return DateTime.UtcNow;
        }
    }

    private static DateTime Max(DateTime left, DateTime right) => left > right ? left : right;

    private static void DeleteDirectory(string directory)
    {
        try
        {
            if (Directory.Exists(directory))
                Directory.Delete(directory, recursive: true);
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            // The cleanup worker tries again; never fail a request on a delete.
        }
    }

    private static void TryDelete(string path)
    {
        try
        {
            if (File.Exists(path))
                File.Delete(path);
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            // Best effort; the session directory delete will retry.
        }
    }

    private static StringComparison PathComparison(string path) =>
        OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
}

internal sealed class SemaphoreLease(SemaphoreSlim gate) : IDisposable
{
    public void Dispose() => gate.Release();
}
